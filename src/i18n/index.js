export function detectDeviceLanguage() {
  try {
    const locales = getLocales();
    const code = locales && locales[0] && locales[0].languageCode;
    return translations[code] ? code : 'zh'; // unknown locales fall back to 中文
  } catch (e) {
    return 'zh';
  }
}

export function translate(lang, key, params) {
  const table = translations[lang] || translations.en;
  let str = table[key] || translations.en[key] || key;
  if (params) {
    Object.keys(params).forEach((p) => {
      str = str.replace(new RegExp(`\\{${p}\\}`, 'g'), String(params[p]));
    });
  }
  return str;
}

export default translations;
